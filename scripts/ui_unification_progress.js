const assert = require("assert/strict");
const fs = require("fs");
const path = require("path");
const { chromium } = require("playwright");
const root = path.resolve(__dirname, "..");
const plan = require("./ui_unification_plan.json");
const output = path.join(root, "docs/analysis/ui-unification-progress.md");
async function main() {
  assert.equal(plan.packages.length, 12);
  assert.equal(new Set(plan.packages.map((item) => item.id)).size, 12);
  for (const item of plan.packages) {
    assert.ok(["pending", "in-progress", "complete"].includes(item.status));
    assert.ok(item.check);
    for (const file of item.files) assert.ok(fs.existsSync(path.join(root, file)), `${item.id}: ${file}`);
    if (item.status === "complete") {
      assert.ok(item.evidence?.length, `${item.id}: completion needs reviewed evidence`);
      for (const file of item.evidence) assert.ok(fs.existsSync(path.join(root, file)), file);
    }
  }
  const browser = await chromium.launch();
  let metrics;
  try {
    const page = await browser.newPage();
    metrics = await page.evaluate((sources) => sources.map(({ file, text }) => {
      const sheet = new CSSStyleSheet(); sheet.replaceSync(text);
      let declarations = 0, surfaces = 0, controls = 0, important = 0;
      const visit = (rules) => { for (const rule of rules) {
        if (rule.cssRules) visit(rule.cssRules);
        if (!rule.selectorText || !rule.style) continue;
        for (const property of rule.style) {
          declarations++;
          if (rule.style.getPropertyPriority(property)) important++;
          const surface = /^(?:background|border|box-shadow|color|font|padding|outline)/.test(property);
          if (surface) surfaces++;
          if (surface && /button|input|select|textarea|tab|token|option|save/.test(rule.selectorText)) controls++;
        }
      }};
      visit(sheet.cssRules);
      return { file, declarations, surfaces, controls, important };
    }), plan.measuredStylesheets.map((file) => ({ file, text: fs.readFileSync(path.join(root, file), "utf8") })));
  } finally { await browser.close(); }
  const complete = plan.packages.filter((item) => item.status === "complete").length;
  const text = ["# UI Unification Progress", "", "Generated by `npm run ui:progress:build`. Do not edit counters by hand.", "",
    "Companion scope and findings: [UI unification audit](ui-unification-audit.md).", "",
    `Completed work packages: **${complete}/${plan.packages.length}**. Infrastructure coverage does not mean page migrations are complete.`, "",
    "## Work Packages", "", "| ID | Scope | Status | Required verification |", "| --- | --- | --- | --- |",
    ...plan.packages.map((item) => `| ${item.id} | ${item.title} | ${item.status} | \`${item.check}\` |`), "",
    "## Remaining Style Footprint", "",
    "CSSOM counts include declarations inside media rules. Surface declarations are background, border, shadow, color, font, padding and outline properties. Control candidates additionally match button/input/select/textarea/tab/token/option/save in their selector. These are review candidates, not a claim that every match is invalid. Geometry is not counted as a surface.", "",
    "| Stylesheet | All declarations | Surface candidates | Control surface candidates | Important |", "| --- | ---: | ---: | ---: | ---: |",
    ...metrics.map((item) => `| ${item.file} | ${item.declarations} | ${item.surfaces} | ${item.controls} | ${item.important} |`), "",
    "## Allowed Domain Styling", "", ...plan.allowedDomainGeometry.map((item) => `- ${item}`), "",
    "## Evidence And Gates", "",
    "- `npm run ui:runtime:check`: live controls, three themes, desktop/mobile, disclosure/tab changes, focus, save/reload and deliberately broken controls.",
    "- `npm run visual:components`: per-component captures plus full-page context; optional reviewed same-platform baseline comparison. This does not replace `visual:catalog`.",
    "- `npm run release:check`: deterministic resource namespace, transitive CSS invalidation, complete offline inventory, rejection of manual version suffixes in published output.",
    "- `npm run ui:progress:check`: rejects stale counters and undocumented completion. It does not infer migration completion from shrinking line counts.", ""].join("\n");
  if (process.argv.includes("--check")) assert.equal(fs.readFileSync(output, "utf8").replace(/\r\n/g, "\n"), text, "Progress report is stale: run npm run ui:progress:build");
  else fs.writeFileSync(output, text);
  console.log(`ok unification progress: ${complete}/12 complete, ${metrics.reduce((sum, item) => sum + item.controls, 0)} control surface candidates`);
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
