const LAZY_ASSET_URLS = new Set(LAZY_ASSETS.map((asset) => new URL(asset, self.registration.scope).href));

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(CORE_ASSETS))
      // Replace old workers immediately after a complete install: the recording
      // was withdrawn, so connected clients must stop serving cached copies.
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME).map((key) => caches.delete(key))))
      // Also remove a restored or previously fetched copy in the current cache.
      .then(() => caches.open(CACHE_NAME))
      .then(async (cache) => {
        const requests = await cache.keys();
        await Promise.all(requests.filter((request) => isRetiredMedia(new URL(request.url))).map((request) => cache.delete(request)));
      })
      .then(() => self.clients.claim())
  );
});

self.addEventListener("message", (event) => {
  if (event.data?.type === "SKIP_WAITING") self.skipWaiting();
});

async function cacheResponse(request, response) {
  if (response && response.ok) {
    const cache = await caches.open(CACHE_NAME);
    await cache.put(request, response.clone());
  }
  return response;
}

async function navigationResponse(request) {
  try {
    return await cacheResponse(request, await fetch(request));
  } catch (error) {
    const exact = await caches.match(request);
    if (exact) return exact;
    const address = new URL(request.url);
    if (address.pathname.endsWith(".html")) {
      address.search = "";
      address.hash = "";
      const page = await caches.match(address.href);
      if (page) return page;
    }
    return caches.match(new URL("index.html", self.registration.scope).href);
  }
}

async function assetResponse(request) {
  const cached = await caches.match(request);
  const network = fetch(request).then((response) => cacheResponse(request, response)).catch(() => cached);
  return cached || network;
}

async function lazyAssetResponse(request) {
  const cached = await caches.match(request);
  if (cached) return cached;
  return cacheResponse(request, await fetch(request));
}

async function mediaResponse(request) {
  const cache = await caches.open(CACHE_NAME);
  let response = await cache.match(request.url);
  if (!response) {
    response = await fetch(request.url);
    if (response.ok && response.status === 200) await cache.put(request.url, response.clone());
  }
  const range = request.headers.get("range");
  if (!range || response.status !== 200) return response;
  const bytes = await response.arrayBuffer();
  const match = /^bytes=(\d*)-(\d*)$/.exec(range);
  const length = bytes.byteLength;
  let start = match?.[1] ? Number(match[1]) : 0;
  let end = match?.[2] ? Number(match[2]) : length - 1;
  if (match && !match[1] && match[2]) { start = Math.max(0, length - end); end = length - 1; }
  if (!match || (!match[1] && !match[2]) || start >= length || end < start) {
    return new Response(null, { status: 416, headers: { "Content-Range": "bytes */" + length } });
  }
  end = Math.min(end, length - 1);
  return new Response(bytes.slice(start, end + 1), { status: 206, headers: {
    "Content-Type": response.headers.get("Content-Type") || (request.url.endsWith(".mp3") ? "audio/mpeg" : "audio/mp4"), "Accept-Ranges": "bytes",
    "Content-Range": "bytes " + start + "-" + end + "/" + length, "Content-Length": String(end - start + 1)
  } });
}

function isRetiredMedia(url) {
  let pathname;
  try { pathname = decodeURIComponent(url.pathname); }
  catch (error) { return false; }
  return /\/assets\/(?:[a-f0-9]{16}\/)?audio\/tonina\.m4a$/.test(pathname);
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin) return;
  // Block retired raw and revisioned URLs before any cache or network fallback.
  if (isRetiredMedia(url)) {
    event.respondWith(Promise.resolve(new Response("This recording is no longer available.", {
      status: 410, headers: { "Content-Type": "text/plain; charset=utf-8", "Cache-Control": "no-store" }
    })));
  } else if (request.mode === "navigate") {
    event.respondWith(navigationResponse(request));
  } else if ((url.pathname.endsWith(".m4a") || url.pathname.endsWith(".mp3")) && LAZY_ASSET_URLS.has(url.href)) {
    event.respondWith(mediaResponse(request));
  } else if (LAZY_ASSET_URLS.has(url.href)) {
    event.respondWith(lazyAssetResponse(request));
  } else {
    event.respondWith(assetResponse(request));
  }
});
